func DecodeBridgeIngestRequest(raw []byte) (BridgeIngestRequest, error) {
	var req BridgeIngestRequest
	fields, err := decodeBridgeRPC(raw, &req, bridgeFields(bridgeHookFields, "event"))
	if err != nil {
		return req, err
	}
	if !validBridgeHook(req.BridgeHookRequest) {
		return req, errors.New("bridge_invalid_input")
	}
	event, err := DecodeBridgeHookEventV1(fields["event"])
	if err != nil {
		return req, err
	}
	if event.BindingID != req.BindingID || event.OwnerEpoch != req.OwnerEpoch {
		return req, errors.New("bridge_invalid_input")
	}
	req.Event = event
	return req, nil
}

