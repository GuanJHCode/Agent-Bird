// PublicBatch copies only v1 model-visible fields from the private IPC reply.
func (reply BridgeClaimReply) PublicBatch() BridgeBatch {
	source := reply.Batch
	public := BridgeBatch{
		SchemaVersion: source.SchemaVersion, BatchID: source.BatchID,
		AttemptID: source.AttemptID, BindingID: source.BindingID,
		OwnerEpoch: source.OwnerEpoch, TransportMode: source.TransportMode,
		RenderSHA256:     source.RenderSHA256,
		Events:           make([]BridgeBatchEvent, len(source.Events)),
		DeliveryReceipts: make([]BridgeDeliveryReceipt, len(source.DeliveryReceipts)),
	}
	for i, event := range source.Events {
		public.Events[i] = BridgeBatchEvent{
			EventID: event.EventID, EventRevision: event.EventRevision,
			EventHash: event.EventHash, ActionSlot: event.ActionSlot,
			TaskID: event.TaskID, WorkRevision: event.WorkRevision,
			Kind: event.Kind, Summary: event.Summary,
		}
		if event.ArtifactRef != nil {
			public.Events[i].ArtifactRef = &BridgeArtifactRef{ID: event.ArtifactRef.ID, SHA256: event.ArtifactRef.SHA256}
		}
	}
	for i, receipt := range source.DeliveryReceipts {
		public.DeliveryReceipts[i] = BridgeDeliveryReceipt{
			TaskID: receipt.TaskID, DeliveryID: receipt.DeliveryID,
			ProofMode: receipt.ProofMode, ProofSHA256: receipt.ProofSHA256,
			EventIDs: append([]string(nil), receipt.EventIDs...),
		}
	}
	return public
}

// DecodeBridgeStrict requires exact declared JSON field names at every object
// depth. encoding/json's struct decoder otherwise accepts case-folded aliases.
func DecodeBridgeStrict(raw []byte, dst any) error {
	if !utf8.Valid(raw) {
		return errors.New("bridge_invalid_input")
	}
	value := reflect.ValueOf(dst)
	if value.Kind() != reflect.Pointer || value.IsNil() || value.Elem().Kind() != reflect.Struct {
		return errors.New("bridge_invalid_input")
	}
	keys := json.NewDecoder(bytes.NewReader(raw))
	if err := bridgeScanValue(keys, value.Elem().Type()); err != nil {
		return fmt.Errorf("bridge_invalid_input: %w", err)
	}
	if _, err := keys.Token(); err != io.EOF {
		return errors.New("bridge_invalid_input")
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	if err := dec.Decode(dst); err != nil {
		return fmt.Errorf("bridge_invalid_input: %w", err)
	}
	if err := dec.Decode(new(any)); err != io.EOF {
		return errors.New("bridge_invalid_input")
	}
	return nil
}

func bridgeScanValue(dec *json.Decoder, target reflect.Type) error {
	for target.Kind() == reflect.Pointer {
		target = target.Elem()
	}
	token, err := dec.Token()
	if err != nil {
		return err
	}
	delim, ok := token.(json.Delim)
	if !ok {
		return nil
	}
	var wantClose json.Delim
	switch delim {
	case '{':
		wantClose = '}'
		if target.Kind() != reflect.Struct {
			return errors.New("object type mismatch")
		}
		allowed := bridgeExactFields(target)
		seen := make(map[string]struct{})
		for dec.More() {
			keyToken, err := dec.Token()
			if err != nil {
				return err
			}
			key, ok := keyToken.(string)
			if !ok {
				return errors.New("non-string key")
			}
			if _, exists := seen[key]; exists {
				return errors.New("duplicate key")
			}
			seen[key] = struct{}{}
			fieldType, allowedKey := allowed[key]
			if !allowedKey {
				return errors.New("unknown field")
			}
			if err := bridgeScanValue(dec, fieldType); err != nil {
				return err
			}
		}
	case '[':
		wantClose = ']'
		if target.Kind() != reflect.Slice && target.Kind() != reflect.Array {
			return errors.New("array type mismatch")
		}
		for dec.More() {
			if err := bridgeScanValue(dec, target.Elem()); err != nil {
				return err
			}
		}
	default:
		return errors.New("invalid delimiter")
	}
	closeToken, err := dec.Token()
	if err != nil {
		return err
	}
	if closeToken != wantClose {
		return errors.New("invalid closing delimiter")
	}
	return nil
}

func bridgeExactFields(target reflect.Type) map[string]reflect.Type {
	allowed := make(map[string]reflect.Type)
	for i := 0; i < target.NumField(); i++ {
		field := target.Field(i)
		if field.PkgPath != "" {
			continue
		}
		tag := field.Tag.Get("json")
		name, _, _ := strings.Cut(tag, ",")
		if name == "-" {
			continue
		}
		if field.Anonymous && name == "" {
			embedded := field.Type
			for embedded.Kind() == reflect.Pointer {
				embedded = embedded.Elem()
			}
			if embedded.Kind() == reflect.Struct {
				for key, child := range bridgeExactFields(embedded) {
					allowed[key] = child
				}
				continue
			}
		}
		if name == "" {
			name = field.Name
		}
		allowed[name] = field.Type
	}
	return allowed
}

var bridgeCommonFields = []string{"schema_version", "binding_id", "owner_epoch", "request_id"}
var bridgeOwnerFields = []string{"schema_version", "binding_id", "owner_epoch", "request_id", "owner_mode", "owner_capability_file", "control_file"}
var bridgeHookFields = []string{"schema_version", "binding_id", "owner_epoch", "request_id", "hook_capability"}

func bridgeFields(base []string, extra ...string) []string {
	fields := append([]string(nil), base...)
	return append(fields, extra...)
}

func decodeBridgeRPC(raw []byte, dst any, required []string) (map[string]json.RawMessage, error) {
	if err := DecodeBridgeStrict(raw, dst); err != nil {
		return nil, err
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(raw, &fields); err != nil {
		return nil, errors.New("bridge_invalid_input")
	}
	for _, name := range required {
		value, ok := fields[name]
		if !ok || bytes.Equal(value, []byte("null")) {
			return nil, errors.New("bridge_invalid_input")
		}
	}
	var version int
	if err := json.Unmarshal(fields["schema_version"], &version); err != nil {
		return nil, errors.New("bridge_invalid_input")
	}
	if version != BridgeSchemaVersion {
		return nil, errors.New("bridge_version_unsupported")
	}
	for name, value := range fields {
		if name != "event" && bytes.Equal(value, []byte("null")) {
			return nil, errors.New("bridge_invalid_input")
		}
	}
	return fields, nil
}

func validBridgeBase(base BridgeRequestBase) bool {
	return base.SchemaVersion == BridgeSchemaVersion && base.BindingID != "" && base.OwnerEpoch > 0 && base.RequestID != ""
}

func validBridgeOwner(req BridgeOwnerRequest) bool {
	return validBridgeBase(req.BridgeRequestBase) && validBridgeOwnerMode(req.OwnerMode) && req.OwnerCapabilityFile != "" && req.ControlFile != ""
}

func validBridgeOwnerMode(mode string) bool {
	return mode == "managed" || mode == "local" || mode == "native"
}

func validBridgeHook(req BridgeHookRequest) bool {
	return validBridgeBase(req.BridgeRequestBase) && req.HookCapability != ""
}

func bridgeSHA256(value string) bool {
	if len(value) != 64 {
		return false
	}
	for _, c := range value {
		if c < '0' || c > '9' && c < 'a' || c > 'f' {
			return false
		}
	}
	return true
}

func DecodeBridgeBindRequest(raw []byte) (BridgeBindRequest, error) {
	var req BridgeBindRequest
	_, err := decodeBridgeRPC(raw, &req, []string{"schema_version", "request_id", "run_id", "provider_id", "native_pid", "native_birth", "native_executable_sha256", "transport_mode", "owner_mode", "owner_capability_file", "control_file", "manifest_sha256"})
	if err != nil {
		return req, err
	}
	if !validBridgeOwnerMode(req.OwnerMode) {
		return req, errors.New("owner_mode_invalid")
	}
	if req.TransportMode != BridgeTransportHookPull {
		return req, errors.New("bridge_mode_unsupported")
	}
	if req.RequestID == "" || req.RunID == "" || req.ProviderID == "" || req.NativePID <= 0 || req.NativeBirth == "" || !bridgeSHA256(req.NativeExecutableSHA256) || req.OwnerCapabilityFile == "" || req.ControlFile == "" || !bridgeSHA256(req.ManifestSHA256) {
		return req, errors.New("bridge_invalid_input")
	}
	return req, nil
}

