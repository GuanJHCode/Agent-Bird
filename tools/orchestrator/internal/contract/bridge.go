func DecodeBridgeHookEventV1(raw []byte) (BridgeHookEventV1, error) {
	var event BridgeHookEventV1
	if len(raw) > 65536 {
		return event, errors.New("bridge_input_too_large")
	}
	if err := DecodeBridgeStrict(raw, &event); err != nil {
		return event, err
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(raw, &fields); err != nil {
		return event, errors.New("bridge_invalid_input")
	}
	for _, name := range []string{"schema_version", "event_id", "binding_id", "owner_epoch", "provider_id", "native_session_id", "native_event_id", "kind", "observed_at", "metadata"} {
		if _, ok := fields[name]; !ok {
			return event, errors.New("bridge_invalid_input")
		}
	}
	var metadata map[string]json.RawMessage
	if bytes.Equal(fields["metadata"], []byte("null")) || json.Unmarshal(fields["metadata"], &metadata) != nil {
		return event, errors.New("bridge_invalid_input")
	}
	for _, name := range []string{"tool_name", "tool_status"} {
		if rawValue, present := metadata[name]; present && (bytes.Equal(rawValue, []byte("null")) || bytes.Equal(rawValue, []byte(`""`))) {
			return event, errors.New("bridge_invalid_input")
		}
	}
	if event.SchemaVersion != 1 {
		return event, errors.New("bridge_version_unsupported")
	}
	if event.EventID == "" || event.BindingID == "" || event.OwnerEpoch == 0 || event.ProviderID == "" || event.NativeSessionID == "" {
		return event, errors.New("bridge_invalid_input")
	}
	switch event.Kind {
	case "session_started", "turn_boundary", "tool_observed", "session_ended":
	default:
		return event, errors.New("bridge_invalid_input")
	}
	if _, err := time.Parse(time.RFC3339Nano, event.ObservedAt); err != nil {
		return event, errors.New("bridge_invalid_input")
	}
	if event.ProviderID == "agy" {
		if !BridgeEmitSupported(event.ProviderID, event.Metadata.NativeHook) || event.Kind != "turn_boundary" || event.Metadata.ToolName != "" || event.Metadata.ToolStatus != "" {
			return event, errors.New("bridge_invalid_input")
		}
	} else if event.Metadata.NativeHook == "PreInvocation" {
		return event, errors.New("bridge_invalid_input")
	}
	switch event.Metadata.NativeHook {
	case "PreInvocation", "SessionStart", "UserPromptSubmit", "PostToolUse", "PostToolUseFailure", "Stop", "SessionEnd":
	default:
		return event, errors.New("bridge_invalid_input")
	}
	switch event.Metadata.ToolStatus {
	case "", "success", "failure", "unknown":
	default:
		return event, errors.New("bridge_invalid_input")
	}
	switch event.Metadata.ToolName {
	case "", "Bash", "Read", "Write", "Edit", "Grep", "Glob", "Task", "WebFetch", "WebSearch", "NotebookEdit":
	default:
		return event, errors.New("bridge_invalid_input")
	}
	return event, nil
}

// BridgeEmitHooks is the single provider/native-hook emission contract.
// Each call returns its own slice; callers cannot change the registered pairs.
func BridgeEmitHooks(provider string) []string {
	switch provider {
	case "claude":
		return []string{"SessionStart", "UserPromptSubmit"}
	case "agy":
		return []string{"PreInvocation"}
	}
	return nil
}
func BridgeEmitSupported(provider, nativeHook string) bool {
	for _, hook := range BridgeEmitHooks(provider) {
		if nativeHook == hook {
			return true
		}
	}
	return false
}
